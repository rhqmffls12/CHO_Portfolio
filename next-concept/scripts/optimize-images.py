"""Generate web derivatives without changing any original portfolio assets.
Run with the bundled workspace Python (Pillow). Regenerates after source changes.
"""
from pathlib import Path
import json
from PIL import Image, ImageOps, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "next-concept" / "assets" / "optimized"
OUT.mkdir(parents=True, exist_ok=True)
manifest = {}
source_bytes = output_bytes = 0
for folder in (ROOT / "assets" / "thumbnails", ROOT / "assets" / "technical"):
    for source in sorted(folder.rglob("*.png")):
        relative = source.relative_to(ROOT).as_posix()
        stem = relative.replace("/", "--").removesuffix(".png")
        item = {}
        with Image.open(source) as original:
            original = ImageOps.exif_transpose(original).convert("RGB")
            item["width"], item["height"] = original.size
            for label, maximum, quality in (("small", 480, 82), ("card", 960, 86), ("detail", 2000, 91)):
                image = original.copy()
                image.thumbnail((maximum, maximum), Image.Resampling.LANCZOS)
                target = OUT / f"{stem}-{label}.webp"
                image.save(target, "WEBP", quality=quality, method=6)
                item[label] = "./" + target.relative_to(ROOT / "next-concept").as_posix()
                output_bytes += target.stat().st_size
        source_bytes += source.stat().st_size
        manifest[relative] = item
(ROOT / "next-concept" / "image-manifest.js").write_text("// Generated by scripts/optimize-images.py; originals are preserved.\nexport const imageManifest = " + json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
# A local social sharing preview using existing portfolio artwork and typography.
preview = Image.new("RGB", (1200, 630), "#f4f5f1")
with Image.open(ROOT / "assets/thumbnails/dednet.png") as artwork:
    preview.paste(ImageOps.fit(artwork.convert("RGB"), (510, 566)), (666, 32))
draw = ImageDraw.Draw(preview)
font_dir = Path("C:/Windows/Fonts")
regular = str(font_dir / "arial.ttf")
bold = str(font_dir / "arialbd.ttf")
draw.text((48, 62), "CHO SEUNGHYUN", font=ImageFont.truetype(bold, 22), fill="#171b18")
draw.text((48, 158), "Art. Tech.", font=ImageFont.truetype(bold, 76), fill="#171b18")
draw.text((48, 244), "Production.", font=ImageFont.truetype(bold, 76), fill="#718b2c")
draw.text((48, 383), "Technical Artist", font=ImageFont.truetype(regular, 29), fill="#435047")
draw.text((48, 434), "Worlds / Rendering / Rigging", font=ImageFont.truetype(regular, 21), fill="#435047")
draw.text((48, 468), "Tools / Workflows / Pipelines", font=ImageFont.truetype(regular, 21), fill="#435047")
preview.save(ROOT / "next-concept/assets/social-preview.jpg", quality=91)
print(f"Generated derivatives for {len(manifest)} images. Originals: {source_bytes / 1048576:.1f} MB; all derivative sizes combined: {output_bytes / 1048576:.1f} MB.")
